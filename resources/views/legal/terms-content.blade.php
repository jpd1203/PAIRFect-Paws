        <h1 id="terms-dialog-title" class="mb-6 font-primary text-3xl font-bold">PAIRfect Paws Terms and Conditions</h1>
        <div class="whitespace-pre-wrap font-secondary text-sm leading-7">By creating an account and using PAIRfect Paws, you agree to use the system responsibly and provide accurate, complete, and truthful information when creating your profile, completing assessments, submitting adoption applications, uploading documents, and participating in adoption and post-adoption activities.

PAIRfect Paws is a digitalized shelter management system designed to support animal record management, adopter profiling, adoption screening, pet-adopter recommendations, applicant management, and post-adoption monitoring.

1. User Account Responsibilities

Users are responsible for providing accurate registration information and for maintaining the confidentiality of their account credentials.

Users must not share their account with unauthorized persons or use another person's account without permission.

Users are responsible for activities performed through their account.

2. Accuracy of Submitted Information

Users must provide truthful and accurate information in adopter profiles, personality assessments, adoption applications, identity documents, interviews, and post-adoption reports.

The submission of false, misleading, altered, or fraudulent information may result in the rejection of an adoption application, suspension of the application process, or restriction of access to the system.

3. Adoption Applications

Submitting an adoption application does not guarantee approval or reservation of an animal.

Applications are subject to review and evaluation by authorized shelter personnel.

The shelter retains the authority to approve or reject an application based on its adoption policies, screening procedures, interviews, animal welfare considerations, and other relevant information.

4. Pet-Adopter Recommendations

PAIRfect Paws uses the K-Nearest Neighbors (KNN) algorithm to generate compatibility-based pet-adopter recommendations.

Compatibility scores and recommendations are intended only as decision-support information.

A high compatibility score does not automatically guarantee adoption approval.

The final adoption decision remains under the authority of authorized shelter personnel.

5. Multiple Applicants for the Same Pet

When multiple eligible applicants apply for the same pet, PAIRfect Paws may rank applicants using their calculated compatibility scores.

Applicants with higher compatibility scores may receive higher priority in the applicant queue.

If two or more applicants have the same compatibility score, the earlier application submission time may be used as a tie-breaker.

When a primary candidate proceeds to the interview stage, the pet may be placed under a Soft-Reserved status and new applications for that pet may temporarily be prevented while the existing applicant queue is being evaluated.

6. Animal Welfare Responsibilities

Users who are approved to adopt an animal are expected to provide proper care, appropriate food and shelter, necessary veterinary attention, protection from cruelty or neglect, and a safe living environment.

Adopters are expected to uphold responsible pet ownership and animal welfare obligations consistent with Republic Act No. 8485, as amended by Republic Act No. 10631.

PAIRfect Paws does not replace the adopter's responsibility to comply with applicable animal welfare laws and shelter policies.

7. Post-Adoption Monitoring

Approved adopters may be required to participate in scheduled post-adoption monitoring conducted through PAIRfect Paws.

This may include welfare check-ins, answering questions regarding the animal's condition and living environment, and submitting supporting photographs or videos.

Post-adoption monitoring is intended to help the shelter assess the animal's adjustment and welfare after placement.

Failure to complete required monitoring activities or the submission of information indicating possible welfare concerns may result in follow-up or further review by authorized shelter personnel.

8. Supporting Documents and Verification

PAIRfect Paws may require supporting documents as part of the adoption screening process.

Submitted information and identification documents may be reviewed or processed using the system's document verification features to help determine whether the information provided is complete and consistent.

Automated verification results are used as decision-support information and may still be reviewed by authorized shelter personnel.

9. Proper Use of the System

Users must not attempt to:

- gain unauthorized access to another user's account or information;
- interfere with the normal operation of PAIRfect Paws;
- submit fraudulent or intentionally misleading information;
- manipulate application, recommendation, or monitoring records;
- misuse information obtained through the system; or
- use PAIRfect Paws for unlawful or harmful activities.

10. Account Restriction

Access to PAIRfect Paws may be restricted or suspended when necessary due to misuse of the system, fraudulent activity, security concerns, violation of shelter policies, or other circumstances requiring administrative action.

11. System Availability

PAIRfect Paws may occasionally become unavailable because of maintenance, technical problems, internet connectivity issues, or other circumstances affecting system operation.

12. Changes to these Terms

The PAIRfect Paws Terms and Conditions may be updated when system functions, shelter procedures, or applicable requirements change.

When appropriate, users may be required to review and accept an updated version before continuing to use affected system functions.</div>
